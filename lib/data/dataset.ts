/**
 * Hitung nilai gizi dan biaya dasar 1 porsi standar untuk setiap resep
 */
function hitungGiziDanBiayaResep(bahanItems: { kode_tkpi: string; jumlah_gram: number }[]): {
  gizi: NilaiGizi;
  biaya_rp: number;
  alergen: string[];
} {
  const gizi: NilaiGizi = {
    energi_kcal: 0,
    protein_g: 0,
    lemak_g: 0,
    karbohidrat_g: 0,
    kalsium_mg: 0,
    zat_besi_mg: 0,
    seng_mg: 0,
    vitamin_a_mcg: 0,
    retinol_mcg: 0,
  };
  let biaya_rp = 0;
  const alergenSet = new Set<string>();

  for (const item of bahanItems) {
    const b = BAHAN_MAP.get(item.kode_tkpi);
    if (!b) continue;

    const fraksi100 = item.jumlah_gram / 100;
    gizi.energi_kcal += b.energi_kcal * fraksi100;
    gizi.protein_g += b.protein_g * fraksi100;
    gizi.lemak_g = (gizi.lemak_g || 0) + b.lemak_g * fraksi100;
    gizi.karbohidrat_g = (gizi.karbohidrat_g || 0) + b.karbohidrat_g * fraksi100;
    gizi.kalsium_mg += b.kalsium_mg * fraksi100;
    gizi.zat_besi_mg += b.zat_besi_mg * fraksi100;
    gizi.seng_mg += b.seng_mg * fraksi100;
    gizi.vitamin_a_mcg += b.vitamin_a_mcg * fraksi100;
    gizi.retinol_mcg = (gizi.retinol_mcg || 0) + (b.retinol_mcg || 0) * fraksi100;

    // Biaya bahan: gram / (BDD/100) / 100 * harga_per_100g (PRD 8.8)
    const bddFactor = (b.bdd_percent > 0 ? b.bdd_percent : 100) / 100;
    const biayaItem = (item.jumlah_gram / bddFactor / 100) * b.harga_per_100g_rp;
    biaya_rp += biayaItem;

    // Alergen diwariskan dari bahan (PRD 8.7)
    for (const a of b.alergen) {
      if (a) alergenSet.add(a.toLowerCase());
    }
  }

  // Bulatkan gizi 1 angka desimal
  return {
    gizi: {
      energi_kcal: Math.round(gizi.energi_kcal * 10) / 10,
      protein_g: Math.round(gizi.protein_g * 10) / 10,
      lemak_g: Math.round((gizi.lemak_g || 0) * 10) / 10,
      karbohidrat_g: Math.round((gizi.karbohidrat_g || 0) * 10) / 10,
      kalsium_mg: Math.round(gizi.kalsium_mg * 10) / 10,
      zat_besi_mg: Math.round(gizi.zat_besi_mg * 10) / 10,
      seng_mg: Math.round(gizi.seng_mg * 10) / 10,
      vitamin_a_mcg: Math.round(gizi.vitamin_a_mcg * 10) / 10,
      retinol_mcg: Math.round((gizi.retinol_mcg || 0) * 10) / 10,
    },
    biaya_rp: Math.round(biaya_rp),
    alergen: Array.from(alergenSet),
  };
}

/**
 * Daftar Resep Lengkap
 */
export const RESEP_LIST: ResepMasakan[] = RESEP_META.map((meta) => {
  const rawItems = RESEP_BAHAN_RAW[meta.kode] || [];
  const { gizi, biaya_rp, alergen } = hitungGiziDanBiayaResep(rawItems);
  const bahanItems = rawItems.map((item) => ({
    kode_tkpi: item.kode_tkpi,
    nama_bahan: BAHAN_MAP.get(item.kode_tkpi)?.nama || item.kode_tkpi,
    jumlah_gram: item.jumlah_gram,
  }));

  return {
    kode: meta.kode,
    nama: meta.nama,
    kategori: meta.kategori,
    porsi_standar: meta.porsi_standar,
    keterangan: meta.keterangan,
    catatan_keamanan: meta.catatan_keamanan,
    target_usia_max_tahun: meta.target_usia_max_tahun,
    bahan: bahanItems,
    alergen,
    gizi_per_porsi: gizi,
    biaya_per_porsi_rp: biaya_rp,
  };
});

export const RESEP_MAP = new Map<string, ResepMasakan>(
  RESEP_LIST.map((r) => [r.kode, r])
);

